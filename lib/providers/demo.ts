function vesselResult(query: string, vessel: TrackingResult["vessel"]): TrackingResult {
  return {
    kind: "vessel",
    query,
    source: "demo",
    carrier: null,
    status: vessel?.navStatus || (vessel?.speed && vessel.speed > 1 ? "Under way" : "Stationary"),
    destination: vessel?.destination ?? null,
    eta: vessel?.eta ?? null,
    vessel,
    events: [
      {
        time: vessel?.lastPositionAt ?? null,
        status: "AIS position",
        location: vessel?.destination ?? null,
        vessel: vessel?.name ?? null,
        voyage: null,
        isActual: true,
      },
    ],
    officialUrls: officialTrackingUrls(vessel?.name || query, "vessel"),
    lastUpdated: vessel?.lastPositionAt ?? null,
  };
}

