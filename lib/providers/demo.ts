export function getDemoResult(
  kind: "container" | "bl" | "vessel",
  normalized: string,
): TrackingResult | null {
  const key = normalized.toUpperCase();
  if (kind === "container") return DEMO_CONTAINERS[key] ?? null;
  if (kind === "bl") return DEMO_BILLS[key] ?? null;
  return DEMO_VESSELS[key] ?? null;
}
